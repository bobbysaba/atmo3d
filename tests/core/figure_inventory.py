"""The inventory of the figure editor's settings (docs-dev/figures-ui-plan.md, Phase 0): every
control the editor shows, on every node of a figure of each kind, with every section and layer
opened.  A control is recorded once per place it is offered:

    level    figure, runs, kind, panel, layer, inset, export, new
    kind     the kind of panel (plan, xsec, ...); "" on figure / runs / export / new
    layer    a layer's or an entry's type (fill, contour, ...); "" elsewhere
    section  the titles of the folds it sits in, outermost first, " > " between
    label    its name, as the user reads it
    control  the widget's class (Select, FloatInput, Checkbox, ...)
    options  a choice's options (at most 40), else []
    keys     the document keys a change to it writes (filled by the second pass), else []

A control only made when another is set a certain way (a contour's levels when contours are on)
was recorded if the figure built then made it.  The old editor is gone (figures-ui-plan.md,
Phase 3.3), so the parts in figure_inventory/ are final: what collected them is deleted."""

import json
import os
from collections import OrderedDict


KINDS = ("plan", "xsec", "th", "line", "sounding", "dist", "profile", "joint", "azim", "table",
         "scene")
PARTS = (*KINDS, "dialogs")  # (stored in STORE: final, the old editor is gone)
HERE = os.path.dirname(os.path.abspath(__file__))
STORE = os.path.join(HERE, "figure_inventory")  # <part>.json
REPORT = os.path.join(HERE, "..", "..", "docs-dev", "figures-inventory.md")


def record_key(rec):
    return "|".join(rec[k] for k in ("level", "kind", "layer", "section", "label", "control"))


def load_part(name):
    with open(os.path.join(STORE, f"{name}.json")) as f:
        return json.load(f)


def report():
    """docs-dev/figures-inventory.md from the stored parts (the same control on several kinds'
    figures, e.g. a Figure-node setting, counted once)."""
    inv, left = OrderedDict(), []
    for name in PARTS:
        got = load_part(name)
        left += got["left"]
        for rec in got["records"]:
            inv.setdefault(record_key(rec), rec)
    write(inv, REPORT, left)
    return len(inv)


def setting_of(key):
    """The setting a document key is, whatever level it is written at: the look's
    style.X / kinds.<kind>.X / panels[].opts.X are look.X; a layer's layers.*.X /
    panels[].layers[].over.X / ...insets[].layers[].over.X are layer.X."""
    import re
    k = re.sub(r"^panels\[\]\.insets\[\]\.", "panels[].", key)
    for pat, to in ((r"^style\.", "look."), (r"^kinds\.\w+\.", "look."),
                    (r"^panels\[\]\.opts\.", "look."), (r"^layers\.\*\.", "layer."),
                    (r"^panels\[\]\.layers\[\]\.over\.", "layer."),
                    (r"^panels\[\]\.layers\[\]\.", "layer.")):
        if re.match(pat, k):
            return re.sub(pat, to, k)
    return k


BROAD = 3  # keys a control writes beyond which it rebuilds rather than sets


def _layer_tag(section):
    import re
    m = re.search(r"\[(\w+)\]", section or "")
    return m.group(1) if m else ""


def place(r):
    return " · ".join(x for x in (r["level"], r["kind"], r["section"]) if x) + f" · {r['label']}"


def write(inv, path_md, left=()):
    rows = list(inv.values())
    mapped = [r for r in rows if r["keys"]]
    # (a control that rewrites more than a few keys rebuilds something: a panel's type, the
    # grid, a field's derivative.  It is listed apart, not as a second control of each.)
    broad = [r for r in mapped if len(r["keys"]) > BROAD]
    by_setting = OrderedDict()
    for r in mapped:
        for k in r["keys"]:
            by_setting.setdefault(setting_of(k), []).append(r)
    twice = OrderedDict()  # (a setting with two controls in one place: level, kind, layer type)
    for s, rs in by_setting.items():
        if s.endswith("[]"):
            continue  # (the parts of a list value: a size's width and height, a box's corners)
        per = OrderedDict()
        for r in rs:
            if len(r["keys"]) > BROAD:
                continue
            per.setdefault((r["level"], r["kind"], r["layer"] or _layer_tag(r["section"])),
                           []).append(r)
        dup = [v for v in per.values() if len({x["label"] for x in v}) > 1]
        if dup:
            twice[s] = dup
    lines = ["# Figure editor inventory", "",
             "Generated by `python tests/core/figure_inventory.py` from the parts collected "
             "from the old editor (docs-dev/figures-ui-plan.md, Phase 0; its screens are gone). One row per control and "
             "place it is offered.", "",
             f"- Controls: {len(rows)}; mapped to the document keys they write: {len(mapped)}; "
             f"the rest write nothing when changed alone (actions, choices that only show "
             f"others, or what this figure cannot change).",
             f"- Settings (document keys, whatever level): {len(by_setting)}.",
             f"- Settings with more than one control in one place (level, kind, layer type): "
             f"{len(twice)} (below).",
             f"- Controls that rewrite more than {BROAD} keys (they rebuild something; not "
             f"counted as second controls): {len(broad)}, e.g. "
             + ", ".join(sorted({r['label'] for r in broad})[:12]) + ".",
             "- Not covered (the test figures cannot make them): "
             + (", ".join(left) if left else "none") + ".", ""]
    lines += ["## Settings with more than one control in one place", "",
              "| Setting | Controls |", "|---|---|"]
    for s, dup in twice.items():
        lines.append(f"| `{s}` | " + "<br>".join("; ".join(place(r) for r in grp)
                                                 for grp in dup) + " |")
    lines += ["", "## Each setting and where it is offered", "", "| Setting | Levels | Controls |",
              "|---|---|---|"]
    for s, rs in sorted(by_setting.items()):
        levels = ", ".join(dict.fromkeys(r["level"] for r in rs))
        lines.append(f"| `{s}` | {levels} | {len(rs)} |")
    by = OrderedDict()
    for r in rows:
        by.setdefault((r["level"], r["kind"]), []).append(r)
    lines += ["", "## Every control", ""]
    for (level, kind), rs in by.items():
        lines += [f"### {level}{' · ' + kind if kind else ''} ({len(rs)})", "",
                  "| Section | Label | Control | Writes |", "|---|---|---|---|"]
        for r in rs:
            lines.append(f"| {r['section']} | {r['label']} | {r['control']} | "
                         f"{', '.join('`' + k + '`' for k in r['keys'])} |")
        lines.append("")
    with open(path_md, "w") as f:
        f.write("\n".join(lines))
    os.chmod(path_md, 0o644)


if __name__ == "__main__":  # python tests/core/figure_inventory.py: the report, from the parts
    print(f"{REPORT}: {report()} controls")


# ------------------------------------------------------------ checked against the schema (Phase 2)
# A control that wrote no key (it was never changed, or it is an action or a dialog's) is answered
# by a schema row of its label, or one of these: a row under another label; a hidden control
# (an entry's head has no on box, but the old row made one); or what the new shell offers it as
# (Phase 3's checklist: a tool, or a dialog's setting, which is not the figure's).
AS_ROW = {"x min (km)": "look.domain.box", "x max (km)": "look.domain.box",
          "y min (km)": "look.domain.box", "y max (km)": "look.domain.box",
          "Row": "panels[].cell", "Column": "panels[].cell", "Rows tall": "panels[].cell",
          "Columns wide": "panels[].cell", "Storm": "runs[].track",
          "New row: time (min)": "layer.edits", "New row: height (km)": "layer.edits",
          "Value": "layer.edits", "Tabulator": "layer.edits", "CodeEditor": "code.text"}
HIDDEN = {("", "Checkbox")}  # (an entry's on box: not shown)
OFFERED_AS = {
    "Add a panel of": "Layout tool: add a panel", "At": "Layout tool: add a panel",
    "Apply a style preset": "Look tool: style presets", "Add": "Marks tool: add an annotation",
    "Add a layer": "Layers tool: add a layer", "Add a layer to this panel": "Layers tool",
    "Copy the look of": "Layers tool: copy a layer's look", "To layers": "Layers tool",
    "+ w budget": "Layers tool: a budget's layers", "Add a run": "Runs tool: add a run",
    "Plain text box": "the code control's own (a plain box when the editor stays blank)",
    "Fill panels": "Layout tool: fill panels"}
DIALOG_ROWS = {"Format": "export.format", "DPI": "export.dpi", "Image size": "export.fit",
               "Margin when trimmed (in)": "export.pad", "Background": "background"}
ITEM_KEYS = [(r"^panels\[\]\.insets\[\]\.layers\[\]\.(over\.)?", "layer.", "inset"),
             (r"^panels\[\]\.layers\[\]\.(over\.)?", "layer.", "panel"),
             (r"^layers\.\*\.", "layer.", "kind"),
             (r"^style\.", "look.", "figure"), (r"^kinds\.(?P<kind>\w+)\.", "look.", "kind"),
             (r"^panels\[\]\.insets\[\]\.opts\.", "look.", "inset"),
             (r"^panels\[\]\.opts\.", "look.", "panel"),
             (r"^panels\[\]\.insets\[\]\.", "insets[].", "inset"),
             (r"^sections\.\w+\.", "sections[].", None)]
SOURCES = {"series": ("series", "series:parcels", "series:table"),
           "profile": ("profile", "profile:table")}
# (the old series card made both its time-series look and its time-height colours, showing one
# by the panel's kind: the inventory has the other's, hidden; units: what Then apply sets)
SERIES_HIDDEN = {("line", k) for k in ("cmap", "reverse", "white_first", "vmin", "vmax",
                                       "nlevels", "extend", "cbar_label", "cbar_ticks")} | \
    {("th", k) for k in ("color", "ls", "lw", "marker", "axis", "ylabel", "units")}


def _schema_aliases(S):
    """{a look key some row writes beside its own (a packed row's others, its also): that row}."""
    out = {}
    for r in S.ROWS:
        block = r.key.rpartition(".")[0]
        if r.key.startswith("look."):
            out.update({f"{block}.{n}": r.key for n in (r.names if r.packed else ())})
            out.update({k: r.key for _, k, _ in r.also})
    return out


def _rows_of(S, key, rec):
    """The rows a document key of a record is (several: a layer key of an entry of any source)."""
    import re
    t = rec["layer"] if rec["layer"] not in ("", "entry") else None
    level = {"runs": "figure", "layer": "panel"}.get(rec["level"], rec["level"])
    for pat, to, at in ITEM_KEYS:
        m = re.match(pat, key)
        if m:
            name = re.sub(r"\[\]$", "", to + key[m.end():])
            level = at or level
            kind = m.groupdict().get("kind")
            break
    else:
        name, kind = {"size_auto": "size"}.get(re.sub(r"\[\]$", "", key), re.sub(
            r"\[\]$", "", key)), None
    if name.startswith("look.") and rec["level"] == "figure":
        level = "figure"  # (the figure node's: a kind's block goes under kinds)
    name = _schema_aliases(S).get(name, name)
    if name.startswith("layer."):
        rows = [S.row_for(name, x) for x in SOURCES.get(t, (t,))] if t else \
            [r for r in S.ROWS if r.key == name]
    else:
        rows = [S.BY_KEY.get(name)]
    return name, [r for r in rows if r is not None], level, kind or rec["kind"] or None


def schema_gaps(records):
    """What of the stored records the settings schema does not offer: (what, why) pairs.  A key
    a control wrote is a row at that record's level, for its kind (and layer type); a control
    that wrote none is a row of its label, or answered above."""
    from atmo3d.figures import schema as S
    labels = {}
    for r in S.ROWS:
        labels.setdefault(r.label.lower(), []).append(r)
    gaps = set()
    for rec in records:
        keys = rec["keys"]
        if len(keys) > BROAD:  # (a rebuild, not a setting's control)
            continue
        if not keys:
            gaps.update(_unkeyed_gap(S, labels, rec))
            continue
        for k in keys:
            name, rows, level, kind = _rows_of(S, k, rec)
            if name in ("size", "size_auto") and level != "figure":
                continue  # (the figure's size follows a panel's change: the shell's)
            if rec["layer"] in ("series", "") and kind and (kind, name[6:]) in SERIES_HIDDEN:
                continue
            if not rows:
                gaps.add((name, "no row"))
            elif not any(r.at(level) for r in rows):
                gaps.add((name, f"not at {level}"))
            elif kind and level != "figure" and not any(kind in r.kinds for r in rows):
                gaps.add((name, f"not for {kind}"))
    return sorted(gaps)


def _unkeyed_gap(S, labels, rec):
    label, ctl, sec = rec["label"], rec["control"], rec["section"]
    if rec["level"] in ("export", "new"):  # (a dialog's: the figure's own export rows, else its)
        return [] if label not in DIALOG_ROWS or sec or DIALOG_ROWS[label] in S.BY_KEY \
            else [(label, "no export row")]
    if (label, ctl) in HIDDEN or sec.split(" > ")[0] in OFFERED_AS or \
            any(label == k or label.startswith(k + " (") for k in OFFERED_AS):
        return []
    want = AS_ROW.get(label) or AS_ROW.get(ctl)
    if want:
        return [] if any(r.id == want or r.id.startswith(want) for r in S.ROWS) else \
            [(label, f"no row {want}")]
    kind = rec["kind"] or None
    hit = [r for r in labels.get(label.lower(), []) if not kind or kind in r.kinds]
    return [] if hit else [(f"{label} ({ctl}, {rec['level']} {kind or ''} {sec})", "no row")]
